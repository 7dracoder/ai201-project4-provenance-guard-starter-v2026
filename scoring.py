"""Combine model and style scores and map every score to a reader label."""

import config


def combine_signals(model_score: float, style_score: float) -> float:
    """Weighted average; higher is more likely AI, not proof of authorship."""
    return round(
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score,
        4,
    )


def score_to_label(score: float) -> tuple[str, str]:
    if score >= config.AI_THRESHOLD:
        return "ai", "We think this may have been generated by AI, but we could be wrong. You can request a review if you wrote it yourself."
    if score <= config.HUMAN_THRESHOLD:
        return "human", "We think this was written by a person, but this estimate is not proof of authorship."
    return "unsure", "We are unsure who wrote this text. This estimate should not be treated as an accusation. You can request a review."


def label_ranges() -> list[tuple[str, str]]:
    return [
        ("high-confidence human", f"0 <= score <= {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} < score < {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} <= score <= 1"),
    ]
